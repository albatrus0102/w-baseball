/// Whether a game can actually be watched in person.
enum AttendanceStatus {
  /// Confirmed open to spectators.
  open,

  /// Confirmed closed / restricted.
  closed,

  /// Not confirmed. This is the default and it is displayed as
  /// "관람 가능 여부 확인 필요" — never assumed to be free and open.
  needsConfirmation;

  static AttendanceStatus parse(String? raw) => switch (raw) {
    'open' => AttendanceStatus.open,
    'closed' => AttendanceStatus.closed,
    _ => AttendanceStatus.needsConfirmation,
  };

  String get wireValue => name;

  String get labelKo => switch (this) {
    AttendanceStatus.open => '관람 가능',
    AttendanceStatus.closed => '관람 불가',
    AttendanceStatus.needsConfirmation => '관람 가능 여부 확인 필요',
  };
}

