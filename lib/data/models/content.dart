/// What a piece of content points at. Uses canonical ids, never name strings,
/// so links survive an upstream API change.
enum ContentEntityKind {
  team,
  person,
  competition,
  season,
  game,
  venue,
  program,
  programSeason,
  episode,
  storyCluster,
  guide;

  static ContentEntityKind parse(String? raw) {
    for (final k in ContentEntityKind.values) {
      if (k.name == raw) return k;
    }
    return ContentEntityKind.team;
  }

  String get wireValue => name;
}

/// Why two things are linked. Keeps "appeared in" distinct from "is actually
/// this player", which matters a great deal for a broadcast.
enum ContentLinkRelation {
  /// Officially confirmed identity link.
  isEntity,

  /// Mentioned or appeared, without an identity claim.
  mentions,

  /// Background reading.
  relatedContext,

  /// The opposing/related real team in a broadcast fixture.
  opponent;

  static ContentLinkRelation parse(String? raw) => switch (raw) {
    'mentions' => ContentLinkRelation.mentions,
    'relatedContext' => ContentLinkRelation.relatedContext,
    'opponent' => ContentLinkRelation.opponent,
    _ => ContentLinkRelation.isEntity,
  };

  String get wireValue => name;

  String get labelKo => switch (this) {
    ContentLinkRelation.isEntity => '공식 확인된 연결',
    ContentLinkRelation.mentions => '언급',
    ContentLinkRelation.relatedContext => '관련 배경',
    ContentLinkRelation.opponent => '상대 팀',
  };
}

@immutable
class ContentEntityLink {
  const ContentEntityLink({
    required this.id,
    required this.fromKind,
    required this.fromId,
    required this.toKind,
    required this.toId,
    required this.relation,
    this.label,
    this.confirmedSourceUrl,
  });

  final String id;
  final ContentEntityKind fromKind;
  final String fromId;
  final ContentEntityKind toKind;
  final String toId;
  final ContentLinkRelation relation;
  final String? label;

  /// Required for [ContentLinkRelation.isEntity]: an identity claim needs a
  /// citation. Validation rejects such a link without one.
  final String? confirmedSourceUrl;

