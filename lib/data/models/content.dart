/// Editorial / discovery content models.
///
/// Design rule that runs through this file: **no programme name is hard-coded
/// anywhere.** `야구여왕 시즌 2` is a row in the `FeaturedTopic` / `Program`
/// tables supplied by remote static config, not an identifier in code. When
/// the season ends, the featured slot falls through to the next topic in the
/// priority list and the programme moves to an archive — no app release.

/// How a summary was produced. Always displayed next to the summary itself.
enum SummaryMethod {
  /// Written by a person.
  manual,

  /// Generated by a deterministic template from structured fields (scores,
  /// dates, counts). Safe because it cannot invent facts.
  template,

  /// Produced with model assistance. Must show the `AI 요약` badge, the
  /// generation time, its sources, and the review status.
  aiAssisted;

  static SummaryMethod parse(String? raw) => switch (raw) {
    'template' => SummaryMethod.template,
    'aiAssisted' => SummaryMethod.aiAssisted,
    _ => SummaryMethod.manual,
  };

  String get wireValue => name;

  String get labelKo => switch (this) {
    SummaryMethod.manual => '직접 작성',
    SummaryMethod.template => '자동 정리',
    SummaryMethod.aiAssisted => 'AI 요약',
  };

  /// AI-assisted summaries must carry a visible badge; the others do not need
  /// to shout, but the method is always available on the detail screen.
  bool get requiresBadge => this == SummaryMethod.aiAssisted;
}

enum ReviewStatus {
  pending,
  reviewed,
  rejected;

  static ReviewStatus parse(String? raw) => switch (raw) {
    'reviewed' => ReviewStatus.reviewed,
    'rejected' => ReviewStatus.rejected,
    _ => ReviewStatus.pending,
  };

  String get wireValue => name;

  String get labelKo => switch (this) {
    ReviewStatus.pending => '검수 전',
    ReviewStatus.reviewed => '검수 완료',
    ReviewStatus.rejected => '검수 반려',
  };
}

/// How complete the underlying data is. Shown wherever a number could be
/// mistaken for a full official tally.
@immutable
class DataCoverage {
  const DataCoverage({
    required this.observed,
    required this.expected,
    this.note,
    this.lastComputedAt,
  });

  /// How many source records we actually hold (e.g. games with box scores).
  final int observed;

  /// How many we believe exist for the scope. Zero means "unknown".
  final int expected;

  final String? note;
  final DateTime? lastComputedAt;

  bool get isUnknown => expected <= 0;

  double? get ratio => isUnknown ? null : (observed / expected).clamp(0.0, 1.0);

  bool get isComplete => !isUnknown && observed >= expected;

  String get labelKo {
    if (isUnknown) return '집계 범위 확인 중';
    if (isComplete) return '전체 $expected경기 집계';
    return '$expected경기 중 $observed경기 집계';
  }

  static const DataCoverage unknown = DataCoverage(observed: 0, expected: 0);
}

/// Content metadata shared by editorial entities.
@immutable
class ContentMeta {
  const ContentMeta({
    required this.provenance,
    required this.publishedAt,
    this.summaryMethod = SummaryMethod.manual,
    this.reviewStatus = ReviewStatus.reviewed,
    this.spoilerLevel = SpoilerLevel.none,
    this.coverage = DataCoverage.unknown,
    this.generatedAt,
  });

  final Provenance provenance;
  final DateTime publishedAt;
  final SummaryMethod summaryMethod;
  final ReviewStatus reviewStatus;
  final SpoilerLevel spoilerLevel;
  final DataCoverage coverage;

  /// When an automated summary was produced. Required for `aiAssisted`.
  final DateTime? generatedAt;

  bool get isDemo => provenance.isDemo;

  /// Whether this record may be shown.
  ///
  /// Deliberately identical to `_check_summary` in
  /// `scripts/validate/validate_data.py`, which is what actually gates
  /// publication: an `aiAssisted` summary needs a human review, a `template`
  /// summary is generated from structured fields and cannot invent anything,
  /// and `manual` text already had a person write it — that person *is* the
  /// human in the loop. A record a reviewer explicitly rejected is never shown,
  /// whatever produced it.
  ///
  /// It used to read `reviewed || template`, which withheld hand-written text
  /// as if a model had produced it. Every record in the shipped seed is
  /// `manual` + `pending`, so that rule hid whatever it was applied to — and it
  /// was applied at exactly one of the ten content types, which is why one
  /// section went dark while nine identical records rendered fine.
  bool get isPublishable {
    // `RecordVisibility` used to be parsed, stored, and checked nowhere, so a
    // record published as `private` or `hidden` rendered exactly like a public
    // one. Content rides in through `ContentSyncEngine`'s ten nested write
    // loops rather than the entity sync path, so it is enforced here — at the
    // gate the repository already consults on every read.
    if (provenance.visibility != RecordVisibility.public) return false;

    return switch (reviewStatus) {
      ReviewStatus.rejected => false,
      ReviewStatus.reviewed => true,
      ReviewStatus.pending => summaryMethod != SummaryMethod.aiAssisted,
    };
  }
}

/// The rotating "what should lead the app right now" slot.
///
/// Priority order lives in data (`featured_topics.json`), so an ended
/// broadcast falls through to the next entry automatically instead of leaving
/// a dead section on the home screen.
enum FeaturedTopicKind {
  /// A currently-airing broadcast or documentary.
  broadcast,

  /// National-team or international competition.
  international,

  /// A major domestic competition.
  domesticCompetition,

  /// A person's or team's story.
  story,

  /// This weekend's games near the user.
  nearbyGames,

  /// Getting-started / training content.
  gettingStarted;

  static FeaturedTopicKind parse(String? raw) => switch (raw) {
    'international' => FeaturedTopicKind.international,
    'domesticCompetition' => FeaturedTopicKind.domesticCompetition,
    'story' => FeaturedTopicKind.story,
    'nearbyGames' => FeaturedTopicKind.nearbyGames,
    'gettingStarted' => FeaturedTopicKind.gettingStarted,
    _ => FeaturedTopicKind.broadcast,
  };

  String get wireValue => name;

  /// Default fallback order when no topic declares an explicit priority.
  /// Mirrors §10 of the product brief.
  int get defaultPriority => switch (this) {
    FeaturedTopicKind.broadcast => 0,
    FeaturedTopicKind.international => 1,
    FeaturedTopicKind.domesticCompetition => 2,
    FeaturedTopicKind.story => 3,
    FeaturedTopicKind.nearbyGames => 4,
    FeaturedTopicKind.gettingStarted => 5,
  };
}

@immutable
class FeaturedTopic {
  const FeaturedTopic({
    required this.id,
    required this.kind,
    required this.title,
    required this.meta,
    this.subtitle,
    this.priority,
    this.programId,
    this.competitionId,
    this.storyClusterId,
    this.guideId,
    this.heroImageUrl,
    this.heroImageLicense = LicenseStatus.unknown,
    this.activeFrom,
    this.activeUntil,
    this.deletedAt,
  });

  final String id;
  final FeaturedTopicKind kind;
  final String title;
  final String? subtitle;

  /// Lower wins. Null falls back to [FeaturedTopicKind.defaultPriority].
  final int? priority;

  /// Exactly one of these points at the thing being featured.
  final String? programId;
  final String? competitionId;
  final String? storyClusterId;
  final String? guideId;

  final String? heroImageUrl;
  final LicenseStatus heroImageLicense;

  /// Outside this window the topic is inactive and something else leads.
  final DateTime? activeFrom;
  final DateTime? activeUntil;

  final ContentMeta meta;
  final DateTime? deletedAt;

  int get effectivePriority => priority ?? kind.defaultPriority;

  bool isActiveAt(DateTime now) {
    if (deletedAt != null) return false;
    final from = activeFrom;
    final until = activeUntil;
    if (from != null && now.isBefore(from)) return false;
    if (until != null && now.isAfter(until)) return false;
    return true;
  }

  bool get canShowHeroImage =>
      heroImageUrl != null &&
      heroImageUrl!.isNotEmpty &&
      heroImageLicense == LicenseStatus.permitted;
}

