/// The two-depth recap. `30초 요약` answers three questions in one sentence
/// each; `3분 이해` adds background and links to real women's baseball.
@immutable
class EpisodeRecap {
  const EpisodeRecap({
    required this.id,
    required this.episodeId,
    required this.meta,
    this.teaser,
    this.whatHappened,
    this.whyItMatters,
    this.whatToWatchNext,
    this.background,
    this.realBaseballContext,
    this.deletedAt,
  });

  final String id;
  final String episodeId;

  /// Spoiler-free one-liner. Always safe to show.
  final String? teaser;

  // 30-second summary: three single sentences.
  final String? whatHappened;
  final String? whyItMatters;
  final String? whatToWatchNext;

  // 3-minute understanding.
  final String? background;
  final String? realBaseballContext;

  final ContentMeta meta;
  final DateTime? deletedAt;

  bool get hasQuickSummary =>
      whatHappened != null || whyItMatters != null || whatToWatchNext != null;

  bool get hasDeepSummary => background != null || realBaseballContext != null;

  /// [teaser] is written to be spoiler-free, so it is what we show when the
  /// user has chosen to hide results.
  String? maskedHeadline(SpoilerPolicy policy) =>
      policy.shouldMask(meta.spoilerLevel) ? teaser : (whatHappened ?? teaser);
}

